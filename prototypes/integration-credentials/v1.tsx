type CredentialsState =
    | { status: 'idle' }
    | { status: 'loading' }
    | { status: 'error' }
    | { status: 'success'; data: CredentialsResponse };

// Credentials stay in this component's state and nowhere else (no store, storage or logs), and they go when the
// dialog unmounts. generate() is the only way to issue them.
const useIntegrationCredentials = (scenario: Scenario) => {
    const [state, setState] = useState<CredentialsState>({ status: 'idle' });
    const token = useRef(0);
    const attempts = useRef(0);

    useEffect(
        () => () => {
            token.current += 1;
        },
        [],
    );

    const generate = useCallback(
        async (request: CredentialsRequest) => {
            token.current += 1;
            const mine = token.current;
            attempts.current += 1;
            setState({ status: 'loading' });
            try {
                const data = await fetchIntegrationCredentials(request, { scenario, attempt: attempts.current });
                if (mine === token.current) {
                    setState({ status: 'success', data });
                }
            } catch {
                if (mine === token.current) {
                    setState({ status: 'error' });
                }
            }
        },
        [scenario],
    );

    return { state, generate };
};

