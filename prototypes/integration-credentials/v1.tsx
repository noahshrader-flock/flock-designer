const IPV4 = /^(25[0-5]|2[0-4]\d|1?\d?\d)(\.(25[0-5]|2[0-4]\d|1?\d?\d)){3}(\/(3[0-2]|[12]?\d))?$/;
const IPV6 = /^[0-9a-fA-F:]+:[0-9a-fA-F:]*(\/(12[0-8]|1[01]\d|\d?\d))?$/;

const parseAllowList = (text: string) =>
    text
        .split(',')
        .map((entry) => entry.trim())
        .filter(Boolean);

const validateAllowList = (text: string): string | null => {
    const entries = parseAllowList(text);
    if (entries.length === 0) {
        return 'Enter at least one IP address or CIDR range, separated by commas.';
    }
    const invalid = entries.filter((entry) => !IPV4.test(entry) && !IPV6.test(entry));
    return invalid.length > 0 ? `Not a valid IP address or CIDR range: ${invalid.join(', ')}` : null;
};

const copyToClipboard = async (text: string) => {
    try {
        await navigator.clipboard.writeText(text);
        return true;
    } catch {
        return false;
    }
};

